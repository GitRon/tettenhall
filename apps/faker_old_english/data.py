"""
The Old English name stock the provider draws from.

Orthography, applied to every entry below without exception:

- **"ae" is written out.** "Aelfred", never "Ælfred" and never the modern "Alfred". The ligature
  reads as an encoding accident wherever a font is missing it, and collapsing it to "e" throws away
  the letter pattern that marks the name stock as English rather than Norse.
- **Thorn and eth resolve to "th".** "Aethelstan", "Cuthbeorht", "Wilfrith". Neither letter is on the
  player's keyboard, and both are the same sound to a reader who is not looking for them.
- **No macrons.** Vowel length carries nothing for anyone reading a war band roster, and half the
  names would need a length mark the sources do not agree on.
- **No Latinised endings.** The charters write "Eadwardus rex"; the man's name is "Eadweard". A "-us"
  on a roster reads as a monk's Latin rather than as anyone's name.

Place-name elements are the first half of a compound and generics the second, so an element is
capitalised and a generic is not: "Stan" + "tun" is "Stantun". Which may follow which is deliberately
unconstrained - every pairing reads as a plausible English place name, and that is what makes a pool
this small go this far.
"""

